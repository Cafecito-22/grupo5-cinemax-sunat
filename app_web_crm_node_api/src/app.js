import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import {api} from './routes/sunat.routes.js';
export const app=express();app.disable('x-powered-by');app.set('trust proxy',1);
app.use(helmet({crossOriginResourcePolicy:{policy:'cross-origin'}}));
const origins=(process.env.FRONTEND_ORIGINS||'http://localhost:5173,http://localhost:5174').split(',').map(x=>x.trim());
app.use(cors({origin:(o,cb)=>cb(null,!o||origins.includes(o)),methods:['GET','POST','PUT','PATCH','DELETE'],allowedHeaders:['Content-Type','Authorization']}));
app.use(express.json({limit:'48kb'}));
app.use('/api',api);
app.use((req,res)=>res.status(404).json({error:'Ruta no encontrada.'}));
app.use((err,req,res,next)=>{if(res.headersSent)return next(err);const status=err.name==='ZodError'?400:err.status||(['23505','23503','23514'].includes(err.code)?409:500);if(status===500)console.error('Error de API',err.code||err.name);res.status(status).json({error:status===500?'No se pudo completar la operación.':err.name==='ZodError'?'Revisa los datos del formulario.':err.code?'Ese registro ya existe o está relacionado con otros datos.':err.message});});
