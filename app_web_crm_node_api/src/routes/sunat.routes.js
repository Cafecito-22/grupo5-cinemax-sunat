import express from 'express';
import {rateLimit} from 'express-rate-limit';
import {auth,permitir,integracion} from '../security.js';
import * as publico from '../controllers/publico.controller.js';
import * as authController from '../controllers/auth.controller.js';
import * as integracionController from '../controllers/integracion.controller.js';
import * as comprobantes from '../controllers/comprobantes.controller.js';
import * as solicitudes from '../controllers/solicitudes.controller.js';
import * as atencion from '../controllers/atencion.controller.js';
import * as perfil from '../controllers/perfil.controller.js';
import * as admin from '../controllers/admin.controller.js';
export const api=express.Router();
const publicoRouter=express.Router(),bridge=express.Router();
const limit=rateLimit({windowMs:15*60*1000,limit:60,standardHeaders:'draft-8',legacyHeaders:false,message:{error:'Demasiados intentos. Vuelve a intentarlo más tarde.'}});
api.use('/publico',publicoRouter);
api.get('/salud',publico.getSalud);
publicoRouter.get('/imagenes/:slug',publico.getImagenesSlug);
api.post('/auth/login',limit,authController.postAuthLogin);
api.post('/auth/registro',limit,authController.postAuthRegistro);
api.use('/integracion',bridge);
bridge.get('/validar',integracion,integracionController.getValidar);
bridge.post('/comprobantes',integracion,integracionController.postComprobantes);
api.use(auth);
api.get('/auth/me',authController.getAuthMe);
api.get('/auth/validar',authController.getAuthValidar);
api.get('/resumen',comprobantes.getResumen);
api.get('/solicitudes',solicitudes.getSolicitudes);
api.post('/solicitudes',permitir('cliente','administrador'),solicitudes.postSolicitudes);
api.put('/solicitudes/:id',permitir('cliente','administrador'),solicitudes.putSolicitudesId);
api.delete('/solicitudes/:id',permitir('cliente','administrador'),solicitudes.deleteSolicitudesId);
api.patch('/solicitudes/:id/estado',permitir('empleado','administrador'),solicitudes.patchSolicitudesIdEstado);
api.get('/solicitudes/:id/historial',solicitudes.getSolicitudesIdHistorial);
api.get('/comprobantes',comprobantes.getComprobantes);
api.get('/fiscalizacion',permitir('empleado','administrador'),comprobantes.getFiscalizacion);
api.get('/observaciones',comprobantes.getObservaciones);
api.post('/observaciones',permitir('empleado','administrador'),comprobantes.postObservaciones);
api.post('/integracion/token',permitir('administrador'),integracionController.postIntegracionToken);
api.get('/integracion/tokens',permitir('administrador'),integracionController.getIntegracionTokens);
api.delete('/integracion/tokens/:jti',permitir('administrador'),integracionController.deleteIntegracionTokensJti);
api.get('/atencion',atencion.getAtencion);
api.post('/atencion',atencion.postAtencion);
api.patch('/atencion/:id',permitir('empleado','administrador'),atencion.patchAtencionId);
api.put('/perfil',perfil.putPerfil);
api.get('/admin/usuarios',permitir('administrador'),admin.getAdminUsuarios);
api.post('/admin/usuarios',permitir('administrador'),admin.postAdminUsuarios);
api.put('/admin/usuarios/:id',permitir('administrador'),admin.putAdminUsuariosId);
api.get('/admin/auditoria',permitir('administrador'),admin.getAdminAuditoria);
